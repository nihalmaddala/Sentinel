// ── Demo Runner ────────────────────────────────────────────────────────────────

function printBanner(text) {
  const line = '═'.repeat(70);
  console.log(`\n${line}`);
  console.log(`  ${text}`);
  console.log(`${line}\n`);
}

function printScenarioHeader(scenario) {
  console.log('\n' + '─'.repeat(70));
  console.log(`  SCENARIO: ${scenario.title}`);
  if (scenario.description) {
    console.log(`  ATTACK:   ${scenario.description}`);
  }
  console.log(`  PR #${scenario.pr.number}: "${scenario.pr.title}"`);
  console.log('─'.repeat(70));
}

async function runScenario(scenario) {
  printScenarioHeader(scenario);

  const ctx = { pr: scenario.pr };
  const report = await scanForInjection(ctx);

  // Print the markdown report to console for demo visibility
  const md = renderInjectionReport(report);
  console.log('\n[demo] ── GITHUB PR COMMENT PREVIEW ──────────────────────────────');
  console.log(md);
  console.log('[demo] ──────────────────────────────────────────────────────────\n');

  return { scenario: scenario.id, status: report.status };
}

async function main() {
  printBanner('ARGUS Security Agent — Prompt Injection Detection Demo');

  const args      = process.argv.slice(2);
  const attackArg = args.indexOf('--attack');
  const cleanOnly = args.includes('--clean');

  let toRun;
  if (cleanOnly) {
    toRun = SCENARIOS.filter(s => s.id === 'clean');
  } else if (attackArg !== -1) {
    const num = parseInt(args[attackArg + 1], 10);
    const id  = `attack${num}`;
    toRun = SCENARIOS.filter(s => s.id === id);
    if (!toRun.length) {
      console.error(`Unknown attack number: ${num}. Use 1, 2, or 3.`);
      process.exit(1);
    }
  } else {
    toRun = SCENARIOS; // Run all
  }

  const results = [];
  for (const scenario of toRun) {
    const r = await runScenario(scenario);
    results.push(r);
  }

  // Final summary
  printBanner('DEMO SUMMARY');
  for (const r of results) {
    const icon   = r.status === 'CLEAN' ? '✅' : r.status === 'BLOCKED' ? '🛡️ ' : '🚨';
    const label  = SCENARIOS.find(s => s.id === r.scenario)?.title || r.scenario;
    console.log(`  ${icon}  ${r.status.padEnd(10)} — ${label}`);
  }

  const detected = results.filter(r => r.status !== 'CLEAN').length;
  if (detected > 0) {
    console.log(`\n  🛡️  Argus detected and blocked ${detected}/${toRun.filter(s => s.id !== 'clean').length} attack(s).`);
    console.log('  No injected PRs reached the compliance pipeline.');
  } else {
    console.log('\n  ✅  All scenarios passed — no attacks in test run.');
  }
  console.log('');
}

main().catch(err => {
  console.error('[demo] Fatal error:', err.message);
  process.exit(1);
});

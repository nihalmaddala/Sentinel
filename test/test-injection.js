const { createHmac } = require('crypto');
const path           = require('path');
require('dotenv').config({ path: path.resolve(__dirname, '../.env') });

const PORT           = process.env.PORT            || 3000;
const WEBHOOK_PATH   = process.env.WEBHOOK_PATH    || '/api/webhook';
const WEBHOOK_SECRET = process.env.GITHUB_WEBHOOK_SECRET;
const TARGET_URL     = `http://localhost:${PORT}${WEBHOOK_PATH}`;

if (!WEBHOOK_SECRET) {
  console.error('[test-injection] FATAL: GITHUB_WEBHOOK_SECRET must be set in .env');
  process.exit(1);
}

const isClean   = process.argv.includes('--clean');
const attackNum = (() => {
  const idx = process.argv.indexOf('--attack');
  return idx !== -1 ? parseInt(process.argv[idx + 1], 10) || 1 : 1;
})();

// ── Payloads ──────────────────────────────────────────────────────────────────


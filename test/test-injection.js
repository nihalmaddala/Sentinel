const ATTACK_DIFFS = { 1: ATTACK_1_DIFF, 2: ATTACK_2_DIFF, 3: ATTACK_3_DIFF };
const ATTACK_NAMES = {
  1: 'Fake Pre-Approval Metadata (stealth bot impersonation)',
  2: 'JSON Termination / Embedded Verdict Injection',
  3: 'Role Reassignment via JSDoc Manipulation',
};

const INJECTED_DIFF = ATTACK_DIFFS[attackNum] || ATTACK_1_DIFF;

const payload = {
  action: 'opened',
  installation: { id: 114607448 },
  pull_request: {
    id:     isClean ? 200 : 201,
    number: isClean ? 200 : 201,
    title:  isClean
      ? 'refactor: improve login validation logic'
      : 'refactor: improve login validation logic', // same title — injection is hidden in diff
    body: 'Small cleanup of the login validation module.',
    head: { sha: 'be6f1d0ebf12bbac3aeb37af3d65654ce99ec297' },
    user: { login: 'dev-engineer' },
  },
  repository: {
    name:      'hackformerced-test',
    full_name: 'nihalmaddala/hackformerced-test',
    owner:     { login: 'nihalmaddala' },
  },
  _diff: isClean ? CLEAN_DIFF : INJECTED_DIFF,
};

const bodyStr  = JSON.stringify(payload);
const signature = 'sha256=' + createHmac('sha256', WEBHOOK_SECRET).update(bodyStr).digest('hex');

async function sendWebhook() {
  const mode = isClean
    ? '✅ CLEAN PR (no injection)'
    : `🔴 ATTACK ${attackNum}: ${ATTACK_NAMES[attackNum] || 'Unknown'}`;

  console.log(`\n[test-injection] ════════════════════════════════════════════`);
  console.log(`[test-injection] Mode: ${mode}`);
  console.log(`[test-injection] Target: POST ${TARGET_URL}`);
  console.log(`[test-injection] ════════════════════════════════════════════\n`);

  if (!isClean) {
    console.log(`[test-injection] Attack type: ${ATTACK_NAMES[attackNum]}`);
    console.log('[test-injection] The injection is HIDDEN in code comments — same PR title as a clean PR');
    console.log('[test-injection] Naive model will be FOOLED. Argus defense will BLOCK.\n');
  }

  const response = await fetch(TARGET_URL, {
    method: 'POST',
    headers: {
      'Content-Type':          'application/json',
      'X-GitHub-Event':        'pull_request',
      'X-Hub-Signature-256':   signature,
      'X-GitHub-Delivery':     `test-injection-${Date.now()}`,
    },
    body: bodyStr,
  });

  const data = await response.json();
  console.log(`[test-injection] Server responded ${response.status}:`, data);
  console.log('\n[test-injection] Watch the server terminal for injection scan results!');
  console.log('[test-injection] Look for: [injection] layer output and INJECTION SCAN RESULT box\n');
}

sendWebhook().catch(console.error);
